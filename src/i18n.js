let lang = 'zh';
export function setLang(l) {
    lang = DICT[l] ? l : 'zh';
}
export function getLang() {
    return lang;
}
export function t(key, params) {
    let s = DICT[lang][key] ?? DICT.zh[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
}
